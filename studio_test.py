from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={"width": 1440, "height": 1000})
    errs = []
    page.on("pageerror", lambda e: errs.append(str(e)))
    page.goto("http://localhost:8098", wait_until="networkidle", timeout=45000)
    page.wait_for_timeout(700)
    page.locator('[data-studio-add="bagan"]').click()
    page.wait_for_timeout(400)
    page.click("#studioGenerate")
    page.wait_for_timeout(3500)
    page.click('[data-ittab="daily"]')
    page.wait_for_timeout(500)
    page.locator('.day-tools [data-regenday]').first.click()
    page.wait_for_timeout(2600)
    print("toast:", page.locator("#toast").inner_text())
    page.click('[data-ittab="budget"]')
    page.wait_for_timeout(500)
    print("donut:", page.locator(".budget-donut").count())
    page.screenshot(path="it-edited.png")
    page.click('[data-ittab="overview"]')
    page.wait_for_timeout(600)
    page.screenshot(path="it-overview-final.png")
    print("errors:", errs[:8])
    b.close()
